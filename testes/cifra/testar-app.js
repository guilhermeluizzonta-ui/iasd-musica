// Testes do "Criar cifra" dentro do app (src/app.html, jsdom). Uso: node testar-app.js ../../src/app.html
const fs = require('fs'); const { JSDOM } = require('jsdom');
const file = process.argv[2] || '../../src/app.html';
const dom = new JSDOM(fs.readFileSync(file, 'utf8'), { runScripts: 'dangerously', pretendToBeVisual: true, url: 'https://exemplo.local/' });
const w = dom.window; let ok = 0, bad = 0;
const t = (name, cond, extra) => { if (cond) ok++; else { bad++; console.log('FALHOU:', name, extra ?? ''); } };
setTimeout(() => {
  const E = (js) => w.eval(js);
  E(`db.user = { name: 'Teste' }; db.role = 'editor'; save(); enterApp();`);
  t('cifras de exemplo abrem no editor visual', E(`activeSongs().every(s => CC.visualOk(s.text))`));
  t('comentário no meio da letra vai para o editor de texto', !E(`CC.visualOk('{title: X}\\n{start_of_verse}\\n[G]a\\n{c: Repete [D] 2x}\\nb\\n{end_of_verse}')`));
  E(`go('cifras'); $('fab').click()`);
  t('+ de Cifras tem Criar cifra primeiro', E(`[...document.querySelectorAll('#fab-menu button')].filter(b => !b.hidden)[0].id`) === 'fab-create');
  E(`$('fab-create').click()`);
  t('abre a ficha', E(`route.name === 'criar' && !$('cc-ficha').hidden && $('cc-doc').hidden`));
  E(`$('cc-f-title').value = 'Nova'; $('cc-f-title').dispatchEvent(new Event('input', { bubbles: true })); document.querySelector('[data-f-key="2"]').click(); document.querySelector('[data-f="ok"]').click()`);
  t('começa com Intro, Estrofe e Refrão no tom D', E(`CC.st.song.key === 'D' && CC.st.song.sections.map(s => s.type).join() === 'intro,estrofe,refrao'`));
  E(`const ta = document.querySelector('textarea.cc-lyr'); ta.value = 'Senhor meu Deus'; ta.dispatchEvent(new Event('input', { bubbles: true }))`);
  t('rascunho guardado ao digitar', JSON.parse(w.localStorage.getItem('cifra-criar.rascunho')).song.sections[1].text === 'Senhor meu Deus');
  E(`$('cc-m-chd').click()`);
  t('paleta aparece no modo Acordes', E(`!$('cc-palette').hidden && document.querySelectorAll('#cc-pal [data-ch="G"]').length === 1`));
  E(`document.querySelector('#cc-pal [data-ch="A"]').dispatchEvent(new MouseEvent('pointerdown', { bubbles: true })); document.dispatchEvent(new MouseEvent('pointerup', { bubbles: true }))`);
  E(`document.querySelector('#cc-doc .cc-ch[data-s="1"][data-i="7"]').click()`);
  t('tocar acorde e depois a sílaba coloca o acorde', E(`CC.toChordPro(CC.st.song)`).includes('Senhor [A]meu Deus'));
  E(`$('cc-save').click()`);
  const s = E(`songById(route.id)`);
  t('salvar vai para a cifra aberta', E(`route.name`) === 'cifra' && s.title === 'Nova' && s.text.includes('{key: D}'));
  t('salvar apaga o rascunho', w.localStorage.getItem('cifra-criar.rascunho') === null);
  t('paleta some fora do editor', E(`$('cc-palette').hidden`));
  E(`$('viewer-edit').click()`);
  t('Editar abre o editor visual', E(`route.name === 'criar' && CC.st.id === '${s.id}'`));
  E(`$('cc-text').click()`);
  t('Editar como texto leva o ChordPro', E(`route.name === 'editor' && $('ed-src').value.includes('[A]meu')`));
  E(`$('ed-visual').click()`);
  t('e volta para o visual', E(`route.name === 'criar' && CC.st.song.title === 'Nova'`));
  E(`$('back-btn').click()`);
  t('voltar leva para a cifra', E(`route.name`) === 'cifra');
  console.log(`${ok} ok, ${bad} falharam`);
  process.exit(bad ? 1 : 0);
}, 400);
